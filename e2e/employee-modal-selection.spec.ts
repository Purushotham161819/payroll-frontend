import { test, expect } from '@playwright/test';
test('modal stays above the directory, traps focus, and closes without saving', async ({page}) => {
  let posts = 0;
  page.on('request', request => { if(request.method() === 'POST') posts++; });
  await page.goto('/');
  const directory = page.locator('.directory');
  const before = await directory.boundingBox();
  const opener = page.getByRole('button', {name:'Add Employee',exact:true}).first();
  await opener.click();
  const dialog = page.getByRole('dialog', {name:'Add employee'});
  await expect(dialog).toBeVisible();
  expect((await directory.boundingBox())?.y).toBe(before?.y);
  await expect(page.getByLabel('First Name', {exact:true})).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByRole('button', {name:'Close add employee'})).toBeFocused();
  await page.getByRole('button', {name:'Close add employee'}).click();
  await expect(dialog).toHaveCount(0);
  await expect(opener).toBeFocused();
  await opener.click();
  await page.getByRole('button', {name:'Cancel',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await opener.click();
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  expect(posts).toBe(0);
  await page.setViewportSize({width:390,height:844});
  await opener.click();
  const bounds = await dialog.boundingBox();
  expect(bounds!.width).toBeLessThanOrEqual(390);
  expect(bounds!.height).toBeLessThanOrEqual(844);
  await expect(page.getByRole('button', {name:'Save employee',exact:true})).toBeInViewport();
});
test('selection uses IDs, reflects all states, and reconciles refresh results', async ({page,request}) => {
  const employees = await (await request.get('http://localhost:3000/employees')).json();
  test.skip(employees.length < 2, 'Needs at least two existing employees; no records are inserted.');
  await page.goto('/');
  const header = page.getByRole('checkbox', {name:'Select all employees',exact:true});
  const row = (id: string) => page.getByRole('checkbox', {name:new RegExp('Select employee .*' + id)});
  await expect(page.getByText('0 employees selected', {exact:true})).toBeVisible();
  await row(employees[0]._id).check();
  await expect(page.getByText('1 employee selected', {exact:true})).toBeVisible();
  await expect(header).toHaveJSProperty('indeterminate',true);
  await header.check();
  await expect(header).toBeChecked();
  await expect(page.getByText(employees.length+' employees selected', {exact:true})).toBeVisible();
  await header.uncheck();
  await expect(page.getByText('0 employees selected', {exact:true})).toBeVisible();
  await expect(header).toHaveJSProperty('indeterminate',false);
  await row(employees[0]._id).focus();
  await page.keyboard.press('Space');
  await expect(row(employees[0]._id)).toBeChecked();
  await page.route('http://localhost:3000/employees', route => route.fulfill({status:200,contentType:'application/json',body:JSON.stringify([...employees].reverse())}));
  await page.getByRole('button',{name:'Refresh list'}).click();
  await expect(row(employees[0]._id)).toBeChecked();
  await page.unroute('http://localhost:3000/employees');
  await page.route('http://localhost:3000/employees', route => route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(employees.slice(1))}));
  await page.getByRole('button',{name:'Refresh list'}).click();
  await expect(page.getByText('0 employees selected', {exact:true})).toBeVisible();
  await expect(header).not.toBeChecked();
});
test('failed save retains data and keeps the modal open; saving prevents cancellation', async ({page,request}) => {
  const employees = await (await request.get('http://localhost:3000/employees')).json();
  const employee = employees.find((employee: any) => employee.email);
  test.skip(!employee, 'Needs an existing employee to reuse values without inventing data.');
  await page.goto('/');
  await page.getByRole('button',{name:'Add Employee',exact:true}).first().click();
  await page.getByLabel('First Name',{exact:true}).fill(employee.firstName);
  await page.getByLabel('Last Name',{exact:true}).fill(employee.lastName);
  await page.getByLabel('Email',{exact:true}).fill(employee.email);
  await page.getByLabel('Date of Birth',{exact:true}).fill(employee.dateOfBirth.slice(0,10));
  await page.getByLabel('Hire Date',{exact:true}).fill(employee.hireDate.slice(0,10));
  await page.getByLabel('Annual CTC',{exact:true}).fill(String(employee.annualCtc));
  let release!: () => void;
  const pending = new Promise<void>(resolve => { release = resolve; });
  await page.route('http://localhost:3000/employees',async route => { await pending; await route.fulfill({status:503,contentType:'application/json',body:'{}'}); });
  await page.getByRole('button',{name:'Save employee',exact:true}).click();
  await expect(page.getByRole('button',{name:'Saving employee…',exact:true})).toBeDisabled();
  await expect(page.getByRole('button',{name:'Cancel',exact:true})).toBeDisabled();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toBeVisible();
  release();
  await expect(page.getByRole('alert')).toContainText('Please try again later');
  await expect(page.getByLabel('First Name',{exact:true})).toHaveValue(employee.firstName);
  await expect(page.getByRole('dialog')).toBeVisible();
});